-- schema-33 (26 Nov 2026): iConnections ingest is LINK-ONLY. A firm that is not in the active iConnections import is
-- staged in ingest_review (to_review) for a person to link or dismiss; it is never added to iconnections_import_*.
-- Matching to the import also tries the firm's linked With Intelligence id and the loose name (Grok's variants such as
-- "MassPrim"). Approved by the user 26 Nov 2026 ("LINK-ONLY: new unmatched firms are staged for review").
-- UNDO: re-apply grok_fn.ingest from schema-31 as of commit f70a3ff; drop table ingest_review (only while empty).

create table if not exists ingest_review (
  id bigint generated by default as identity primary key,
  run_tag text not null, source text not null check (source in ('iconnections', 'preqin', 'opportunities')),
  firm_key text not null, name text not null, wi_id text, opportunity_id bigint references wi_mandates(id),
  match jsonb, row_data jsonb not null default '{}'::jsonb,
  status text not null default 'to_review' check (status in ('to_review', 'linked', 'dismissed')),
  by_whom text, created_at timestamptz not null default now(), reviewed_by text, reviewed_at timestamptz
);
create unique index if not exists ingest_review_open on ingest_review (source, firm_key) where status = 'to_review';
alter table ingest_review enable row level security;
drop policy if exists console_read on ingest_review;
create policy console_read on ingest_review for select using (is_console_user());
drop policy if exists console_edit on ingest_review;
create policy console_edit on ingest_review for update using (is_console_user()) with check (is_console_user());
drop policy if exists automation_full on ingest_review;
create policy automation_full on ingest_review to taranis_bot using (true) with check (true);

create or replace function grok_fn.ingest(p_source text, p_rows jsonb, p_dry_run boolean default true,
                                          p_by text default 'Grok', p_file jsonb default '{}'::jsonb, p_plan text default null)
returns jsonb language plpgsql security definer set search_path to 'public', 'pg_temp' as $$
declare
  plan text; tag text; r jsonb; k text; nm text; m jsonb; fld jsonb; items jsonb := '[]'; idx jsonb := '{}';
  ins jsonb := '[]'; upd jsonb := '[]'; skp jsonb := '[]'; con jsonb := '[]';
  chunk jsonb; res jsonb; it jsonb; i int; run_id bigint; row_no int := 0; cur record; changes jsonb; c jsonb;
  firm record; latest record; save_tags text[] := '{}'; v text; aum numeric; wi text; lr jsonb;
  cols text[] := array['domain', 'aum_text', 'aum_low', 'aum_high', 'investor_type', 'country', 'city', 'strategies',
                       'asset_classes', 'ticket_min_usd', 'ticket_max_usd', 'wi_id', 'preqin_id', 'summary', 'people',
                       'contacts_detail', 'email_domains'];
  icols text[] := array['domain', 'aum_text', 'aum_low', 'aum_high', 'investor_type', 'country', 'people', 'contacts_detail', 'email_domains'];
  col text; sets text[]; n_upd int := 0; alias jsonb := '{}'; rev jsonb := '[]';
begin
  if p_source not in ('opportunities', 'iconnections', 'preqin') then raise exception 'source is opportunities, iconnections or preqin.'; end if;
  if p_rows is null or jsonb_typeof(p_rows) <> 'array' or jsonb_array_length(p_rows) = 0 then raise exception 'Give rows: a list.'; end if;
  if jsonb_array_length(p_rows) > 1000 then raise exception 'At most 1000 rows per upload.'; end if;
  plan := md5(p_source || '|' || p_rows::text);
  if not p_dry_run and p_plan is distinct from plan then
    raise exception 'Run a dry run of these exact rows first and send its plan_id with dry_run false.';
  end if;
  tag := 'ingest-' || p_source || '-' || to_char(clock_timestamp(), 'YYYYMMDD-HH24MISS') || '-' || substr(plan, 1, 6);

  -- 4a. De-duplicate inside the upload: same domain or same firm name -> one row, blanks merged.
  for r in select value from jsonb_array_elements(p_rows) loop
    nm := nullif(btrim(r ->> 'name'), '');
    if jsonb_typeof(r) <> 'object' or nm is null then skp := skp || jsonb_build_object('name', coalesce(r ->> 'name', '?'), 'reason', 'No firm name.'); continue; end if;
    -- the same firm by domain OR by name (a later line may lack the domain): alias map -> first key
    k := coalesce(alias ->> nullif(lower(btrim(r ->> 'domain')), ''), alias ->> grok_fn.firm_key(nm),
                  nullif(lower(btrim(r ->> 'domain')), ''), grok_fn.firm_key(nm));
    alias := alias || jsonb_build_object(grok_fn.firm_key(nm), k)
                   || case when nullif(lower(btrim(r ->> 'domain')), '') is null then '{}'::jsonb
                           else jsonb_build_object(lower(btrim(r ->> 'domain')), k) end;
    if idx ? k then
      idx := jsonb_set(idx, array[k], (select coalesce(jsonb_object_agg(e.key, e.value), '{}') from jsonb_each(r) e
               where not (idx -> k ? e.key) or idx -> k -> e.key in ('null'::jsonb, '""'::jsonb, '[]'::jsonb)) || (idx -> k)
               || jsonb_build_object('_dupes', coalesce((idx -> k ->> '_dupes')::int, 0) + 1));
      skp := skp || jsonb_build_object('name', nm, 'reason', 'Repeated in this upload: merged into one row.');
    else
      idx := idx || jsonb_build_object(k, jsonb_strip_nulls(r));
    end if;
  end loop;

  for k, r in select key, value from jsonb_each(idx) loop
    nm := btrim(r ->> 'name');
    wi := coalesce(nullif(btrim(r ->> 'wi_id'), ''), substring(r ->> 'wi_url' from 'investors/(-?\d+)'));
    m := grok_fn.match_mandate(nm, wi);
    aum := coalesce((r ->> 'aum_usd')::numeric, case when (r ->> 'aum_low') = (r ->> 'aum_high') then (r ->> 'aum_low')::numeric end);

    -- 4b. Opportunities: fill blanks on the matched investor through grok_fn.save (scope mandates).
    if p_source = 'opportunities' then
      if m ->> 'status' = 'conflict' then
        con := con || jsonb_build_object('name', nm, 'reason', 'Several Opportunities match this name: choose one.', 'candidates', m -> 'candidates'); continue;
      elsif m ->> 'status' = 'none' then
        skp := skp || jsonb_build_object('name', nm, 'reason', 'Not in Opportunities. Uploads never create Opportunities: send it with discover (it needs a With Intelligence id).',
                                         'wi_id', wi); continue;
      end if;
      -- CLAUDE.md rule 4: Andrew Carnegie (1358) is never changed by anything automatic.
      if (m ->> 'id')::bigint = 1358 then
        skp := skp || jsonb_build_object('name', nm, 'id', m -> 'id', 'reason', 'Protected row (Andrew Carnegie, 1358): never changed by an upload.'); continue;
      end if;
      fld := jsonb_strip_nulls(jsonb_build_object(
        'investor_type', r -> 'investor_type', 'country', r -> 'country', 'city', r -> 'city',
        'aum_usd', to_jsonb(aum), 'aum_band', case when aum is null and r ? 'aum_low' then r -> 'aum_text' end,
        'asset_classes', r -> 'asset_classes', 'strategies', r -> 'strategies',
        'ticket_min_usd', r -> 'ticket_min_usd', 'ticket_max_usd', r -> 'ticket_max_usd', 'min_manager_aum_usd', r -> 'min_manager_aum_usd',
        'open_to_emerging_managers', r -> 'open_to_emerging_managers', 'emerging_evidence', r -> 'emerging_evidence',
        'tech_focus', r -> 'tech_focus', 'tech_evidence', r -> 'tech_evidence', 'summary', r -> 'summary'));
      if fld = '{}'::jsonb and wi is null then skp := skp || jsonb_build_object('name', nm, 'id', m -> 'id', 'reason', 'No fields to fill.'); continue; end if;
      items := items || jsonb_strip_nulls(jsonb_build_object('id', (m ->> 'id'), 'wi_id', wi, 'fields', fld, '_name', nm, '_match', m));

    -- 4c. iConnections, LINK-ONLY (26 Nov 2026): fill blanks on the firm's row in the active import. A firm not in
    --     the import is NOT added: it is staged in ingest_review for a person to link or dismiss.
    --     Match: exact firm key, then the firm's linked With Intelligence id, then the loose name (one firm only).
    elsif p_source = 'iconnections' then
      select * into firm from grok.iconn_firms f where f.firm_key = grok_fn.firm_key(nm) limit 1;
      if not found and wi is not null then
        select * into firm from grok.iconn_firms f where f.wi_investor_id = wi order by f.firm_key limit 1;
      end if;
      if not found and (select count(*) from grok.iconn_firms f where grok_fn.loose_key(f.firm_name) = grok_fn.loose_key(nm)) = 1 then
        select * into firm from grok.iconn_firms f where grok_fn.loose_key(f.firm_name) = grok_fn.loose_key(nm);
      end if;
      if firm.firm_key is not null then
        select x.* into latest from iconnections_import_rows x join iconnections_import_runs u on u.id = x.run_id and u.import_no = x.import_no and u.hidden_at is null
         where coalesce(nullif(x.norm_name, ''), lower(x.name)) = firm.firm_key order by u.last_matched_at desc nulls last, x.run_id desc, x.row_no limit 1;
        lr := to_jsonb(latest); changes := '[]'; sets := '{}';
        foreach col in array icols loop
          if r ? col and (lr -> col is null or lr -> col in ('null'::jsonb, '""'::jsonb, '[]'::jsonb)) then
            changes := changes || jsonb_build_object('field', col, 'old', null, 'new', r -> col);
            sets := sets || format('%I = (jsonb_populate_record(null::iconnections_import_rows, %L::jsonb)).%I', col, jsonb_build_object(col, r -> col)::text, col);
          end if;
        end loop;
        res := null;
        if wi is not null then   -- a With Intelligence profile for the firm: candidate for review, never auto-linked
          res := grok_fn.save('iconnections', jsonb_build_array(jsonb_strip_nulls(jsonb_build_object('id', firm.firm_key, 'wi_id', wi, 'certain', false,
                   'fields', jsonb_strip_nulls(jsonb_build_object('name', r -> 'name', 'investor_type', r -> 'investor_type', 'country', r -> 'country',
                                                                    'aum_usd', to_jsonb(aum), 'strategies', r -> 'strategies', 'asset_classes', r -> 'asset_classes'))))),
                   p_dry_run, p_by);
          if res ->> 'run' is not null then save_tags := save_tags || (res ->> 'run'); end if;
          changes := changes || jsonb_build_object('field', 'with_intelligence', 'result', res -> 'items' -> 0);
        end if;
        if cardinality(sets) = 0 and (wi is null or coalesce(res -> 'items' -> 0 ->> 'status', '') not in ('saved', 'would_save')) then
          skp := skp || jsonb_build_object('name', nm, 'reason', 'Already in the iConnections import; nothing blank to fill.',
                                           'with_intelligence', case when wi is not null then res -> 'items' -> 0 end);
          continue;
        end if;
        if not p_dry_run and cardinality(sets) > 0 then
          execute format('update iconnections_import_rows set %s where run_id = $1 and row_no = $2', array_to_string(sets, ', ')) using latest.run_id, latest.row_no;
          insert into ingest_log (run_tag, source, target_table, target_id, firm, field, old_value, new_value, by_whom)
          select tag, p_source, 'iconnections_import_rows', latest.run_id || ':' || latest.row_no, nm, c ->> 'field', null, c ->> 'new', p_by
            from jsonb_array_elements(changes) c where c ? 'new';
        end if;
        upd := upd || jsonb_build_object('name', nm, 'firm_key', firm.firm_key, 'changes', changes);
      else
        if (select count(*) from ingest_review v where v.source = p_source and v.firm_key = grok_fn.firm_key(nm) and v.status = 'to_review') > 0 then
          skp := skp || jsonb_build_object('name', nm, 'reason', 'Not in the iConnections import; already waiting for review.');
          continue;
        end if;
        if not p_dry_run then
          insert into ingest_review (run_tag, source, firm_key, name, wi_id, opportunity_id, match, row_data, by_whom)
          values (tag, p_source, grok_fn.firm_key(nm), nm, wi, (m ->> 'id')::bigint, m, r, p_by);
          insert into ingest_log (run_tag, source, target_table, target_id, firm, field, new_value, by_whom)
          values (tag, p_source, 'ingest_review', currval(pg_get_serial_sequence('ingest_review', 'id'))::text, nm, 'staged_for_review', left(r::text, 2000), p_by);
        end if;
        rev := rev || jsonb_build_object('name', nm, 'wi_id', wi, 'match', m ->> 'status', 'opportunity', m -> 'id', 'verdict', m -> 'verdict');
      end if;

    -- 4d. Preqin: one live row per firm; fill blanks on it, or add it.
    else
      select * into cur from preqin_import_rows p
       where p.deleted_at is null and (p.firm_key = grok_fn.firm_key(nm) or (r ->> 'domain' is not null and lower(p.domain) = lower(r ->> 'domain')))
       order by (p.firm_key = grok_fn.firm_key(nm)) desc limit 1;
      if found then
        lr := to_jsonb(cur); changes := '[]'; sets := '{}';
        foreach col in array cols loop
          if r ? col and (lr -> col is null or lr -> col in ('null'::jsonb, '""'::jsonb, '[]'::jsonb)) then
            changes := changes || jsonb_build_object('field', col, 'old', null, 'new', r -> col);
            sets := sets || format('%I = (jsonb_populate_record(null::preqin_import_rows, %L::jsonb)).%I', col, jsonb_build_object(col, r -> col)::text, col);
          end if;
        end loop;
        if cur.matched_id is null and m ->> 'status' = 'matched' then
          changes := changes || jsonb_build_object('field', 'matched_id', 'old', null, 'new', m -> 'id');
          sets := sets || format('matched_id = %s, matched_name = %L, matched_status = %L, matched_fit = %L::numeric, matched_fit_reason = %L, match_method = %L, bucket = %L, matched_at = now()',
                                 (m ->> 'id')::bigint, m ->> 'name', m ->> 'verdict', m ->> 'fit', m ->> 'reason', m ->> 'how', 'matched');
        end if;
        if cardinality(sets) = 0 then skp := skp || jsonb_build_object('name', nm, 'reason', 'Already staged from Preqin; nothing blank to fill.'); continue; end if;
        if not p_dry_run then
          execute format('update preqin_import_rows set %s, updated_at = now(), field_sources = field_sources || $2 where id = $1', array_to_string(sets, ', '))
            using cur.id, (select jsonb_object_agg(c ->> 'field', jsonb_build_object('by', p_by, 'via', 'grok ingest', 'source', 'preqin', 'run', tag, 'at', now()))
                             from jsonb_array_elements(changes) c);
          insert into ingest_log (run_tag, source, target_table, target_id, firm, field, old_value, new_value, by_whom)
          select tag, p_source, 'preqin_import_rows', cur.id::text, nm, c ->> 'field', null, c ->> 'new', p_by from jsonb_array_elements(changes) c;
        end if;
        upd := upd || jsonb_build_object('name', nm, 'row_id', cur.id, 'changes', changes);
      else
        if run_id is null and not p_dry_run then
          insert into preqin_import_runs (run_tag, file_sha256, file_name, sheet_name, columns, row_count, created_by, matched_by)
          values (tag, encode(sha256(convert_to(plan || '|preqin', 'UTF8')), 'hex'), coalesce(p_file ->> 'file_name', 'Grok upload'), p_file ->> 'sheet_name',
                  coalesce(p_file -> 'columns', '{}'), jsonb_array_length(p_rows), p_by, 'Grok ingest')
          returning id into run_id;
        end if;
        row_no := row_no + 1;
        if not p_dry_run then
          insert into preqin_import_rows (run_id, last_run_id, row_no, firm_key, raw, name, domain, aum_text, aum_low, aum_high, investor_type, country, city,
                 strategies, asset_classes, ticket_min_usd, ticket_max_usd, wi_id, preqin_id, summary, norm_name, bucket, match_method, confidence,
                 matched_id, matched_name, matched_status, matched_fit, matched_fit_reason, candidates, people, contacts_detail, email_domains,
                 field_sources, matched_at)
          values (run_id, run_id, row_no, grok_fn.firm_key(nm), coalesce(r -> 'raw', r), nm, r ->> 'domain', r ->> 'aum_text', (r ->> 'aum_low')::numeric,
                 (r ->> 'aum_high')::numeric, r ->> 'investor_type', r ->> 'country', r ->> 'city',
                 (select array_agg(x) from jsonb_array_elements_text(r -> 'strategies') x), (select array_agg(x) from jsonb_array_elements_text(r -> 'asset_classes') x),
                 (r ->> 'ticket_min_usd')::numeric, (r ->> 'ticket_max_usd')::numeric, wi, r ->> 'preqin_id', r ->> 'summary', grok_fn.loose_key(nm),
                 case m ->> 'status' when 'matched' then 'matched' when 'conflict' then 'review' else 'none' end,
                 case when m ->> 'how' in ('exact', 'alias', 'wi_id') then m ->> 'how' end, case when m ->> 'status' = 'matched' then 'Grok ingest' end,
                 (m ->> 'id')::bigint, m ->> 'name', m ->> 'verdict', (m ->> 'fit')::numeric, m ->> 'reason', m -> 'candidates',
                 (select array_agg(x) from jsonb_array_elements_text(r -> 'people') x), r -> 'contacts_detail',
                 (select array_agg(x) from jsonb_array_elements_text(r -> 'email_domains') x),
                 jsonb_build_object('row', jsonb_build_object('by', p_by, 'via', 'grok ingest', 'source', 'preqin', 'run', tag, 'at', now())),
                 case when m ->> 'status' = 'matched' then now() end);
          insert into ingest_log (run_tag, source, target_table, target_id, firm, field, new_value, by_whom)
          values (tag, p_source, 'preqin_import_rows', currval(pg_get_serial_sequence('preqin_import_rows', 'id'))::text, nm, 'row', left(r::text, 2000), p_by);
        end if;
        ins := ins || jsonb_build_object('name', nm, 'match', m ->> 'status', 'opportunity', m -> 'id', 'verdict', m -> 'verdict');
        if m ->> 'status' = 'conflict' then con := con || jsonb_build_object('name', nm, 'reason', 'Staged; several Opportunities match: choose one on the card.', 'candidates', m -> 'candidates'); end if;
      end if;
    end if;
  end loop;

  -- 4e. Opportunities: grok_fn.save in batches of 20 (its own dry run, checks, verdict guard and wi_fill_log).
  if p_source = 'opportunities' then
    i := 0;
    while i < jsonb_array_length(items) loop
      select jsonb_agg(e - '_name' - '_match') into chunk from (select value e from jsonb_array_elements(items) with ordinality o(value, n) where n > i and n <= i + 20) s;
      res := grok_fn.save('mandates', chunk, p_dry_run, p_by);
      if res ->> 'run' is not null then save_tags := save_tags || (res ->> 'run'); end if;
      for it in select value from jsonb_array_elements(res -> 'items') loop
        nm := (select e ->> '_name' from jsonb_array_elements(items) e where e ->> 'id' = it ->> 'id' limit 1);
        if it ->> 'status' = 'error' then
          if it ->> 'error' ~* 'verdict' then
            con := con || jsonb_build_object('name', nm, 'id', it -> 'id', 'reason', 'Would change the verdict: left for review. ' || (it ->> 'error'));
          elsif it ->> 'error' ~* 'rejected|merged|not_an_allocator' then
            skp := skp || jsonb_build_object('name', nm, 'id', it -> 'id', 'reason', it ->> 'error');
          else
            con := con || jsonb_build_object('name', nm, 'id', it -> 'id', 'reason', it ->> 'error');
          end if;
        elsif (select coalesce(sum(jsonb_array_length(x -> 'saved')), 0) from jsonb_array_elements(it -> 'result') x) = 0 then
          skp := skp || jsonb_build_object('name', nm, 'id', it -> 'id', 'reason', 'Nothing blank to fill.', 'skipped_fields', it -> 'skipped_fields');
        else
          upd := upd || jsonb_build_object('name', nm, 'id', it -> 'id', 'rows', it -> 'result', 'skipped_fields', it -> 'skipped_fields');
        end if;
      end loop;
      i := i + 20;
    end loop;
  end if;

  -- 4f. field_sources on the Opportunities just filled (provenance per field), from the save runs' log lines.
  if not p_dry_run and cardinality(save_tags) > 0 then
    update wi_mandates w set field_sources = (case when jsonb_typeof(w.field_sources) = 'object' then w.field_sources else '{}'::jsonb end) || s.fs
      from (select l.mandate_id, jsonb_object_agg(l.field, jsonb_build_object('by', p_by, 'via', 'grok ingest', 'source', p_source,
                     'run', tag, 'save_run', t, 'at', l.filled_at)) fs
              from wi_fill_log l, unnest(save_tags) t
             where l.source like 'Grok · ' || t || '%' and l.mandate_id is not null and l.field !~ '^iconnections\.'
             group by l.mandate_id, t) s
     where w.id = s.mandate_id;
  end if;

  return jsonb_build_object('source', p_source, 'dry_run', p_dry_run, 'plan_id', plan,
    'run', case when not p_dry_run then tag end, 'save_runs', to_jsonb(save_tags),
    'summary', jsonb_build_object('inserted', jsonb_array_length(ins), 'updated', jsonb_array_length(upd),
                                  'skipped', jsonb_array_length(skp), 'conflicts', jsonb_array_length(con),
                                  'staged_for_review', jsonb_array_length(rev)),
    'inserted', ins, 'updated', upd, 'skipped', skp, 'conflicts', con, 'staged_for_review', rev,
    'note', case when p_dry_run then 'Dry run: nothing was written. To write exactly this, send the same rows with dry_run false and this plan_id.'
                 else 'Written. Opportunities changes: wi_fill_log (save_runs; undo with save_undo). Staging changes: ingest_log run ' || tag || '.' end);
end $$;

revoke all on function grok_fn.ingest(text, jsonb, boolean, text, jsonb, text) from public, anon, authenticated;

--
-- Contract (same as grok_fn.save):
--   * dry run by default; a real write needs the plan_id that the dry run of the SAME rows returned,
--   * blanks are filled, nothing that has a value is overwritten,
--   * every value written is logged: Opportunities through grok_fn.save (wi_fill_log),
--     staging rows (iConnections, Preqin) in ingest_log, and field_sources is stamped,
--   * uploads never create Opportunities. Unmatched investors are staged (iConnections, Preqin)
--     or reported (opportunities source) for discover / review.
--   * verdicts are never written here: wi_mandates triggers score the row; if a fill would change
--     a verdict, grok_fn.save refuses it (VERDICT_GUARD) and it comes back as a conflict.

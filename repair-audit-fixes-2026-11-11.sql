create table wi_mandates_backup_20261111_audit as
  select id, qualification, new_qualification, new_fit_score, fit_reason, hf_held_verdict, hf_held_score,
         approved_at, approved_by, validation_status, merged_into, evidence, verdict_source
    from wi_mandates where id in (select id from fix_verdict union select id from fix_merge union select keeper from fix_merge);

insert into wi_fill_log (mandate_id, investor_name, field, old_value, new_value, source)
select m.id, m.investor_name, 'Verdict', concat_ws(' ', coalesce(m.new_qualification, m.qualification), coalesce(m.new_fit_score::text, '-')),
       concat_ws(' ', f.q, coalesce(f.s::text, '-')), 'Audit fix 11 Nov 2026 (decided by research@taranis.net): ' || f.note
  from wi_mandates m join fix_verdict f on f.id = m.id
 where coalesce(m.verdict_source, '') <> 'manual';   -- never a verdict a person set
update wi_mandates m set new_qualification = f.q, qualification = case when f.q in ('matched', 'rejected') then f.q else 'uncertain' end,
       new_fit_score = f.s, fit_reason = f.note || ' ' || coalesce(m.fit_reason, ''),
       hf_held_verdict = null, hf_held_score = null
  from fix_verdict f where f.id = m.id and coalesce(m.verdict_source, '') <> 'manual';

update wi_mandates k set
  evidence = (case when jsonb_typeof(k.evidence) = 'object' then k.evidence else '{}'::jsonb end)
             || jsonb_build_object('merged_rows', coalesce(case when jsonb_typeof(k.evidence) = 'object' then k.evidence -> 'merged_rows' end, '[]'::jsonb) || x.rows)
  from (select f.keeper, jsonb_agg(jsonb_build_object(
          'id', m.id, 'summary', m.intention_summary, 'tag', m.investor_tag, 'intention_url', m.view_intention_url,
          'article_url', m.view_article_url, 'alert_date', m.alert_date, 'verdict', coalesce(m.new_qualification, m.qualification),
          'score', m.new_fit_score, 'verdict_source', m.verdict_source, 'reason', m.hard_fail_reasons,
          'approved_at', m.approved_at, 'approved_by', m.approved_by, 'source_message_id', m.source_message_id) order by m.alert_date desc nulls last) rows
          from fix_merge f join wi_mandates m on m.id = f.id group by f.keeper) x
 where k.id = x.keeper;
insert into wi_fill_log (mandate_id, investor_name, field, old_value, new_value, source)
select m.id, m.investor_name, 'Merged into row', coalesce(m.validation_status, ''), f.keeper::text,
       'Audit merge 11 Nov 2026 (decided by research@taranis.net): same investor, one row per investor'
  from wi_mandates m join fix_merge f on f.id = m.id;
update wi_mandates m set validation_status = 'merged', merged_into = f.keeper from fix_merge f where f.id = m.id;
update iconnections_import_rows r set matched_id = f.keeper from fix_merge f where r.matched_id = f.id;

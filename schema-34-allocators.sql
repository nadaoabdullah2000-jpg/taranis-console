-- schema-34 (26 Nov 2026): the enriched allocator file (tab "Enriched") in the console.
-- Additive: new table allocators, new view allocators_view, new functions. Nothing existing is changed.
--   * allocators: one row per allocator (de-duplicated by name, then With Intelligence id); full text kept, never
--     truncated; contacts parsed by enriched.js. Tier: 1 Strong, 2 Tech, 3 Emerging Managers, 4 Opportunities.
--   * allocators_view: each allocator with its Opportunity (matched by With Intelligence id) for the fields the file
--     does not carry (bio, tickets, fit score, With Intelligence match, hedge fund evidence, space, currency), and the
--     "Needs Review" flag: With Intelligence match status is not Correct, or Preqin is not confirmed (no Preqin link).
--   * grok_fn.ingest_allocators: dry run by default; a write needs the dry run's plan_id. New allocator -> insert;
--     existing -> the file's values replace the stored ones in allocators (the user's choice, 26 Nov: "file wins"),
--     every changed value logged in ingest_log. Opportunities (wi_mandates) are NOT written here.
--   * console_ingest_allocators: the console's upload button (signed-in console users only) calls the same function.
-- UNDO: drop function console_ingest_allocators(jsonb, boolean, text, jsonb); drop function grok_fn.ingest_allocators(jsonb, boolean, text, jsonb, text);
--       drop function grok_fn.allocator_tier(text, text, text, text); drop view allocators_view; then soft-delete
--       (update allocators set deleted_at = now()) - the table itself is dropped only on request, while empty.

create table if not exists allocators (
  id bigint generated by default as identity primary key,
  name text not null, name_key text not null,
  wi_id text, wi_url text,
  intention text,
  tech text check (tech in ('Yes', 'No', 'Not stated')),
  emerging text check (emerging in ('Yes', 'No', 'Not stated')),
  contacts jsonb not null default '[]'::jsonb, contacts_raw text,
  iconn_url text, iconn_contacts jsonb not null default '[]'::jsonb, iconn_contacts_raw text, iconn_notes text,
  fit_status text, preqin_url text, iconn_bot_data text,
  tier smallint not null check (tier between 1 and 4), tier_label text not null,
  source_file text, source_row integer,
  field_sources jsonb not null default '{}'::jsonb,
  first_run text, last_run text,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now(), deleted_at timestamptz
);
create unique index if not exists allocators_name_live on allocators (name_key) where deleted_at is null;
create index if not exists allocators_wi on allocators (wi_id) where deleted_at is null;
alter table allocators enable row level security;
drop policy if exists console_read on allocators;
create policy console_read on allocators for select using (is_console_user());
drop policy if exists automation_full on allocators;
create policy automation_full on allocators to taranis_bot using (true) with check (true);

-- The tier rule, the same as enriched.js tierOf() and the file's own Fit Status formula.
create or replace function grok_fn.allocator_tier(p_fit text, p_tech text, p_emerging text, p_iconn text)
returns smallint language sql immutable as $$
  select (case
    when lower(btrim(coalesce(p_fit, ''))) = 'strong' or (p_tech = 'Yes' and p_emerging = 'Yes' and nullif(btrim(p_iconn), '') is not null) then 1
    when p_tech = 'Yes' then 2
    when p_emerging = 'Yes' then 3
    else 4 end)::smallint
$$;

create or replace view allocators_view with (security_invoker = true) as
select a.*,
       m.id mandate_id, m.investor_name mandate_name, m.investor_type, m.investor_country, m.investor_city,
       m.aum_usd, m.aum_band, m.ticket_min_usd, m.ticket_max_usd, m.ticket_currency, m.min_manager_aum_usd,
       coalesce(m.new_fit_score, m.fit_score) fit_score, coalesce(nullif(m.new_qualification, ''), m.qualification) verdict,
       m.verdict_source, m.strategies, m.source_kind,
       case when jsonb_typeof(m.evidence) = 'object' then m.evidence ->> 'wi_summary' end wi_summary,
       m.wi_match_status, m.wi_match_note, m.wi_match_checked_at,
       m.hf_evidence, m.hf_evidence_note, m.hf_evidence_source, m.hf_checked_at,
       m.is_tech_investor, m.tech_signal, m.is_space, m.space_signal, m.intention_summary,
       (m.wi_match_status is distinct from 'Correct') or a.preqin_url is null needs_review,
       array_remove(array[
         case when m.id is null then 'Not in Opportunities: With Intelligence match not checked'
              when m.wi_match_status is distinct from 'Correct' then 'With Intelligence match: ' || coalesce(m.wi_match_status, 'not checked') end,
         case when a.preqin_url is null then 'Preqin not confirmed' end], null) review_reasons
  from allocators a
  left join lateral (
    select * from wi_mandates w
     where a.wi_id is not null and jsonb_typeof(w.evidence) = 'object' and w.evidence ->> 'wi_investor_id' = a.wi_id
       and coalesce(w.validation_status, '') not in ('pending', 'merged')
     order by (coalesce(nullif(w.new_qualification, ''), w.qualification) = 'rejected'), coalesce(w.new_fit_score, w.fit_score) desc nulls last, w.id
     limit 1) m on true
 where a.deleted_at is null;
grant select on allocators_view to authenticated;

create or replace function grok_fn.ingest_allocators(p_rows jsonb, p_dry_run boolean default true, p_by text default 'Grok',
                                                     p_file jsonb default '{}'::jsonb, p_plan text default null)
returns jsonb language plpgsql security definer set search_path to 'public', 'pg_temp' as $$
declare
  plan text := md5('allocators|' || coalesce(p_rows::text, ''));
  tag text := 'allocators-' || to_char(clock_timestamp(), 'YYYYMMDD-HH24MISS') || '-' || substr(md5(coalesce(p_rows::text, '')), 1, 6);
  r jsonb; k text; nm text; cur allocators; seen jsonb := '{}'; changes jsonb; f text; tier smallint;
  fields text[] := array['name', 'wi_id', 'wi_url', 'intention', 'tech', 'emerging', 'contacts', 'contacts_raw', 'iconn_url',
                         'iconn_contacts', 'iconn_contacts_raw', 'iconn_notes', 'fit_status', 'preqin_url', 'iconn_bot_data'];
  newrec jsonb; oldrec jsonb; sets text[];
  ins jsonb := '[]'; upd jsonb := '[]'; same int := 0; skp jsonb := '[]'; tiers jsonb := '{"1":0,"2":0,"3":0,"4":0}';
begin
  if p_rows is null or jsonb_typeof(p_rows) <> 'array' or jsonb_array_length(p_rows) = 0 then raise exception 'Give rows: a list.'; end if;
  if jsonb_array_length(p_rows) > 5000 then raise exception 'At most 5000 rows per upload.'; end if;
  if not p_dry_run and p_plan is distinct from plan then
    raise exception 'Run a dry run of these exact rows first and send its plan_id with dry_run false.';
  end if;
  for r in select value from jsonb_array_elements(p_rows) loop
    nm := nullif(btrim(r ->> 'name'), '');
    if jsonb_typeof(r) <> 'object' or nm is null then skp := skp || jsonb_build_object('row', r -> 'source_row', 'reason', 'No allocator name.'); continue; end if;
    k := lower(regexp_replace(nm, '\s+', ' ', 'g'));
    if seen ? k or (nullif(r ->> 'wi_id', '') is not null and seen ? ('wi:' || (r ->> 'wi_id'))) then
      skp := skp || jsonb_build_object('name', nm, 'reason', 'Repeated in this upload (same name or With Intelligence id): first row kept.'); continue;
    end if;
    seen := seen || jsonb_build_object(k, true) || case when nullif(r ->> 'wi_id', '') is not null then jsonb_build_object('wi:' || (r ->> 'wi_id'), true) else '{}' end;
    tier := grok_fn.allocator_tier(r ->> 'fit_status', r ->> 'tech', r ->> 'emerging', r ->> 'iconn_url');
    tiers := jsonb_set(tiers, array[tier::text], to_jsonb((tiers ->> tier::text)::int + 1));
    newrec := jsonb_build_object('name', nm, 'wi_id', nullif(r ->> 'wi_id', ''), 'wi_url', nullif(r ->> 'wi_url', ''),
      'intention', r ->> 'intention', 'tech', coalesce(nullif(r ->> 'tech', ''), 'Not stated'), 'emerging', coalesce(nullif(r ->> 'emerging', ''), 'Not stated'),
      'contacts', coalesce(r -> 'contacts', '[]'), 'contacts_raw', r ->> 'contacts_raw', 'iconn_url', nullif(r ->> 'iconn_url', ''),
      'iconn_contacts', coalesce(r -> 'iconn_contacts', '[]'), 'iconn_contacts_raw', r ->> 'iconn_contacts_raw', 'iconn_notes', r ->> 'iconn_notes',
      'fit_status', r ->> 'fit_status', 'preqin_url', nullif(r ->> 'preqin_url', ''), 'iconn_bot_data', r ->> 'iconn_bot_data');
    select * into cur from allocators a where a.deleted_at is null and (a.name_key = k or (a.wi_id is not null and a.wi_id = newrec ->> 'wi_id'))
     order by (a.name_key = k) desc limit 1;
    if not found then
      if not p_dry_run then
        insert into allocators (name, name_key, wi_id, wi_url, intention, tech, emerging, contacts, contacts_raw, iconn_url, iconn_contacts,
                                iconn_contacts_raw, iconn_notes, fit_status, preqin_url, iconn_bot_data, tier, tier_label, source_file, source_row,
                                field_sources, first_run, last_run)
        values (nm, k, newrec ->> 'wi_id', newrec ->> 'wi_url', newrec ->> 'intention', newrec ->> 'tech', newrec ->> 'emerging', newrec -> 'contacts',
                newrec ->> 'contacts_raw', newrec ->> 'iconn_url', newrec -> 'iconn_contacts', newrec ->> 'iconn_contacts_raw', newrec ->> 'iconn_notes',
                newrec ->> 'fit_status', newrec ->> 'preqin_url', newrec ->> 'iconn_bot_data', tier,
                (array['Strong', 'Tech', 'Emerging Managers', 'Opportunities'])[tier], p_file ->> 'file_name', (r ->> 'source_row')::int,
                jsonb_build_object('row', jsonb_build_object('by', p_by, 'run', tag, 'file', p_file ->> 'file_name', 'at', now())), tag, tag);
        insert into ingest_log (run_tag, source, target_table, target_id, firm, field, new_value, by_whom)
        values (tag, 'allocators', 'allocators', currval(pg_get_serial_sequence('allocators', 'id'))::text, nm, 'row', left(newrec::text, 8000), p_by);
      end if;
      ins := ins || jsonb_build_object('name', nm, 'tier', tier);
    else
      oldrec := to_jsonb(cur); changes := '[]'; sets := '{}';
      foreach f in array fields loop
        if (oldrec -> f) is distinct from (newrec -> f) and not (coalesce(oldrec -> f, 'null') in ('null', '""', '[]') and coalesce(newrec -> f, 'null') in ('null', '""', '[]')) then
          changes := changes || jsonb_build_object('field', f, 'old', oldrec -> f, 'new', newrec -> f);
          sets := sets || format('%I = (jsonb_populate_record(null::allocators, %L::jsonb)).%I', f, jsonb_build_object(f, newrec -> f)::text, f);
        end if;
      end loop;
      if cur.tier <> tier then
        changes := changes || jsonb_build_object('field', 'tier', 'old', cur.tier_label, 'new', (array['Strong', 'Tech', 'Emerging Managers', 'Opportunities'])[tier]);
        sets := sets || format('tier = %s, tier_label = %L', tier, (array['Strong', 'Tech', 'Emerging Managers', 'Opportunities'])[tier]);
      end if;
      if cardinality(sets) = 0 then same := same + 1; continue; end if;
      if not p_dry_run then
        execute format('update allocators set %s, name_key = $2, last_run = $3, updated_at = now(), source_file = $4, source_row = $5, field_sources = field_sources || $6 where id = $1',
                       array_to_string(sets, ', '))
          using cur.id, k, tag, p_file ->> 'file_name', (r ->> 'source_row')::int,
                (select jsonb_object_agg(c ->> 'field', jsonb_build_object('by', p_by, 'run', tag, 'file', p_file ->> 'file_name', 'at', now())) from jsonb_array_elements(changes) c);
        insert into ingest_log (run_tag, source, target_table, target_id, firm, field, old_value, new_value, by_whom)
        select tag, 'allocators', 'allocators', cur.id::text, nm, c ->> 'field', left(c ->> 'old', 8000), left(c ->> 'new', 8000), p_by from jsonb_array_elements(changes) c;
      end if;
      upd := upd || jsonb_build_object('name', nm, 'id', cur.id, 'changed', (select jsonb_agg(c ->> 'field') from jsonb_array_elements(changes) c));
    end if;
  end loop;
  return jsonb_build_object('dry_run', p_dry_run, 'plan_id', plan, 'run', case when not p_dry_run then tag end,
    'summary', jsonb_build_object('inserted', jsonb_array_length(ins), 'updated', jsonb_array_length(upd), 'unchanged', same,
                                  'skipped', jsonb_array_length(skp), 'tiers', jsonb_build_object('Strong', tiers -> '1', 'Tech', tiers -> '2',
                                  'Emerging Managers', tiers -> '3', 'Opportunities', tiers -> '4')),
    'inserted', ins, 'updated', upd, 'skipped', skp,
    'note', case when p_dry_run then 'Dry run: nothing was written. To write exactly this, send the same rows with dry_run false and this plan_id.'
                 else 'Written. Every change is in ingest_log run ' || tag || '.' end);
end $$;
revoke all on function grok_fn.ingest_allocators(jsonb, boolean, text, jsonb, text) from public, anon, authenticated;

-- The console upload: same function, by the signed-in console user.
create or replace function public.console_ingest_allocators(p_rows jsonb, p_dry_run boolean default true, p_plan text default null,
                                                            p_file jsonb default '{}'::jsonb)
returns jsonb language plpgsql security definer set search_path to 'public', 'pg_temp' as $$
begin
  if not is_console_user() then raise exception 'Only console users can upload allocators.'; end if;
  return grok_fn.ingest_allocators(p_rows, p_dry_run, coalesce(auth.jwt() ->> 'email', 'console'), p_file, p_plan);
end $$;
revoke all on function public.console_ingest_allocators(jsonb, boolean, text, jsonb) from public, anon;
grant execute on function public.console_ingest_allocators(jsonb, boolean, text, jsonb) to authenticated;
